const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { io } = require('socket.io-client');
const { createApp } = require('../server');
const defaults = require('../config');

test('HTTP scenarios and Socket.IO snapshot/diffs work end to end', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ember-test-'));
  let now = 100000;
  const app = createApp({ directory, config: { ...defaults, HEARTBEAT_INTERVAL_MS: 100000, STATE_INTERVAL_MS: 100000 }, clock: () => now, random: () => .5 });
  const address = await app.start(0);
  const base = `http://127.0.0.1:${address.port}`;
  const socket = io(`${base}/live`, { transports: ['websocket'], autoConnect: false });
  t.after(async () => { socket.close(); await app.stop(); fs.rmSync(directory, { recursive: true, force: true }); });
  const event = name => new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error(`Timed out waiting for ${name}`)), 3000); socket.once(name, value => { clearTimeout(timeout); resolve(value); }); });
  const initialEvent = event('snapshot'); socket.connect();
  const initial = await initialEvent;
  assert.deepEqual(initial.summary, { expected: 40, safe: 0, unaccounted: 4, active_sos: 0 });
  assert.ok(fs.existsSync(path.join(directory, 'fingerprint_map.json')));
  assert.ok(initial.devices.every(d => !Object.hasOwn(d, 'true_floor') && !Object.hasOwn(d, 'true_xy')));
  const post = (route, body) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const diffEvent = event('state_diff');
  assert.equal((await post('/simulate/sos', { device_id: 'D001' })).status, 200);
  const diff = await diffEvent;
  assert.equal(diff.devices.length, 1); assert.equal(diff.devices[0].status, 'active_sos');
  assert.equal((await (await fetch(base + '/api/summary')).json()).active_sos, 1);
  assert.equal((await post('/simulate/go-silent', { device_id: 'D002' })).status, 200);
  now += 9000;
  const floor = await (await fetch(base + '/api/floors/4')).json();
  assert.equal(floor.devices.find(d => d.device_id === 'D002').status, 'heartbeat_lost');
  await post('/simulate/ap-down', { ap_id: 'AP-10' });
  await post('/simulate/power-outage', { floor: 4 });
  const outage = await (await fetch(base + '/api/floors/4')).json();
  assert.equal(outage.offline_aps, 3);
  assert.equal((await (await fetch(base + '/api/summary')).json()).unaccounted, 4);
  await post('/simulate/evacuate', { device_id: 'D001' });
  assert.equal((await (await fetch(base + '/api/summary')).json()).safe, 1);
  for (const [route, body] of [['/simulate/sos', { device_id: 'D999' }], ['/simulate/ap-down', { ap_id: 'AP-999' }], ['/simulate/power-outage', { floor: 99 }], ['/api/heartbeat', { device_id: 'D001', raw_pressure: 101277, raw_rssi: {}, floor: 1 }]]) assert.equal((await post(route, body)).status, 400);
  assert.equal((await fetch(base + '/api/floors/0')).status, 400);
  assert.equal((await fetch(base + '/')).status, 200);
  const resetEvent = event('snapshot'); await post('/simulate/reset', {});
  const reset = await resetEvent;
  assert.equal(reset.summary.safe, 0); assert.equal(reset.summary.unaccounted, 4);
  assert.ok(reset.aps.every(ap => ap.online));
});
